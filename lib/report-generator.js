/**
 * mSAS v2 — Unified Report Generator
 * 
 * Produces MASTG-compliant reports with CVSS 3.1 scoring.
 * Works across APK, IPA, and ADB auditors.
 */

var MSAS = MSAS || {};
MSAS.ReportGenerator = (function() {
  'use strict';

  /**
   * Generates a summary object from an array of test results
   * @param {Array} results - Array of TestResult objects
   * @returns {Object} { total, passed, failed, bySeverity, score, grade }
   */
  function summarize(results) {
    if (!results || !results.length) {
      return { total: 0, passed: 0, failed: 0, bySeverity: {}, score: 0, grade: 'N/A' };
    }

    var total = results.length;
    var passed = results.filter(function(r) { return r.passed; }).length;
    var failed = total - passed;
    var bySeverity = MSAS.TestResult ? { critical: 0, high: 0, medium: 0, low: 0, info: 0 } : {};
    
    results.forEach(function(r) {
      if (bySeverity[r.severity] !== undefined) bySeverity[r.severity]++;
    });

    // Security score: 100 - (weighted failures)
    var weights = { critical: 25, high: 15, medium: 10, low: 5, info: 1 };
    var penalty = 0;
    results.forEach(function(r) {
      if (!r.passed && weights[r.severity]) {
        penalty += weights[r.severity];
      }
    });
    var score = Math.max(0, Math.min(100, 100 - penalty));

    var grade = 'A';
    if (score < 30) grade = 'F';
    else if (score < 50) grade = 'D';
    else if (score < 70) grade = 'C';
    else if (score < 90) grade = 'B';

    return { total: total, passed: passed, failed: failed, bySeverity: bySeverity, score: Math.round(score), grade: grade };
  }

  /**
   * Generates a MASTG-compliant report text (plain-text summary)
   * @param {Object} options
   * @param {string} options.appName      - App name
   * @param {string} options.auditorType  - 'APK', 'IPA', or 'ADB'
   * @param {Array}  options.results      - Test results
   * @param {number} [options.durationMs] - Analysis duration
   * @returns {string} Formatted report text
   */
  function generateReportText(options) {
    var opts = options || {};
    var results = opts.results || [];
    var summary = summarize(results);
    var lines = [];

    lines.push('========================================');
    lines.push('  mSAS — Mobile Security Analysis Suite');
    lines.push('  MASTG-Compliant Security Report');
    lines.push('========================================');
    lines.push('');
    lines.push('  App:          ' + (opts.appName || 'Unknown'));
    lines.push('  Auditor:      ' + (opts.auditorType || 'General'));
    lines.push('  Timestamp:    ' + new Date().toISOString());
    lines.push('  Duration:     ' + (opts.durationMs ? (opts.durationMs / 1000).toFixed(1) + 's' : 'N/A'));
    lines.push('');

    // Risk score
    lines.push('  Security Score: ' + summary.score + '/100  (Grade: ' + summary.grade + ')');
    lines.push('  Total Checks:   ' + summary.total);
    lines.push('  Passed:         ' + summary.passed);
    lines.push('  Failed:         ' + summary.failed);
    lines.push('');

    // Severity breakdown
    lines.push('  --- Severity Breakdown ---');
    var sevs = ['critical', 'high', 'medium', 'low', 'info'];
    for (var i = 0; i < sevs.length; i++) {
      var count = summary.bySeverity[sevs[i]] || 0;
      if (count > 0) {
        lines.push('    ' + sevs[i].charAt(0).toUpperCase() + sevs[i].slice(1) + ': ' + count);
      }
    }
    lines.push('');

    // Findings
    var findings = results.filter(function(r) { return !r.passed; });
    if (findings.length > 0) {
      lines.push('  --- Findings ---');
      findings.forEach(function(f) {
        lines.push('');
        lines.push('  [' + f.severity.toUpperCase() + '] ' + f.title);
        lines.push('  ID:    ' + f.id);
        if (f.mastgRef) lines.push('  Ref:   ' + f.mastgRef);
        lines.push('  Desc:  ' + f.description);
        if (f.remediation) lines.push('  Fix:   ' + f.remediation);
      });
    } else {
      lines.push('  No findings — all checks passed.');
    }

    lines.push('');
    lines.push('========================================');
    lines.push('  Generated by mSAS v2');
    lines.push('========================================');

    return lines.join('\n');
  }

  /**
   * Generates HTML report content
   * @param {Object} options - Same as generateReportText
   * @returns {string} HTML string
   */
  function generateReportHtml(options) {
    var opts = options || {};
    var results = opts.results || [];
    var summary = summarize(results);
    var ts = new Date().toISOString();

    var html = '<!DOCTYPE html><html><head><meta charset="utf-8">';
    html += '<title>mSAS Report — ' + escapeHtml(opts.appName || 'Security Audit') + '</title>';
    html += '<style>body{font-family:-apple-system,BlinkMacSystemFont,sans-serif;background:#0a0e17;color:#e2e8f0;padding:40px;max-width:900px;margin:0 auto}';
    html += 'h1{color:#6366f1}table{border-collapse:collapse;width:100%}th,td{text-align:left;padding:10px;border-bottom:1px solid #1e2d4a}';
    html += '.severity-critical{color:#ef4444}.severity-high{color:#f97316}.severity-medium{color:#eab308}.severity-low{color:#22c55e}.severity-info{color:#3b82f6}';
    html += '.finding{margin:12px 0;padding:16px;border-radius:8px;border:1px solid #1e2d4a;background:#111827}';
    html += '.finding-title{font-weight:600;font-size:1rem}.finding-desc{color:#8892a4;font-size:0.875rem}';
    html += '.score{font-size:2rem;font-weight:700}.grade{font-size:1.25rem;margin-left:12px}';
    html += '</style></head><body>';

    html += '<h1>🔒 mSAS Security Report</h1>';
    html += '<p><strong>App:</strong> ' + escapeHtml(opts.appName || 'Unknown') + ' | ';
    html += '<strong>Auditor:</strong> ' + escapeHtml(opts.auditorType || 'General') + ' | ';
    html += '<strong>Date:</strong> ' + ts + '</p>';

    html += '<h2>Summary</h2>';
    html += '<p><span class="score">' + summary.score + '/100</span>';
    html += '<span class="grade">Grade: ' + summary.grade + '</span></p>';
    html += '<table><tr><th>Total</th><th>Passed</th><th>Failed</th>';
    html += '<th>Critical</th><th>High</th><th>Medium</th><th>Low</th></tr>';
    html += '<tr><td>' + summary.total + '</td><td>' + summary.passed + '</td><td>' + summary.failed + '</td>';
    html += '<td style="color:#ef4444">' + (summary.bySeverity.critical||0) + '</td>';
    html += '<td style="color:#f97316">' + (summary.bySeverity.high||0) + '</td>';
    html += '<td style="color:#eab308">' + (summary.bySeverity.medium||0) + '</td>';
    html += '<td style="color:#22c55e">' + (summary.bySeverity.low||0) + '</td></tr></table>';

    var findings = results.filter(function(r) { return !r.passed; });
    if (findings.length > 0) {
      html += '<h2>Findings (' + findings.length + ')</h2>';
      findings.forEach(function(f) {
        html += '<div class="finding">';
        html += '<div class="finding-title"><span class="severity-' + f.severity + '">[' + f.severity.toUpperCase() + ']</span> ' + escapeHtml(f.title) + '</div>';
        html += '<div class="finding-desc">' + escapeHtml(f.description) + '</div>';
        if (f.mastgRef) html += '<div style="font-size:0.8rem;color:#5a6478;margin-top:4px">Ref: ' + escapeHtml(f.mastgRef) + '</div>';
        if (f.remediation) html += '<div style="font-size:0.8rem;color:#22c55e;margin-top:4px">Fix: ' + escapeHtml(f.remediation) + '</div>';
        html += '</div>';
      });
    } else {
      html += '<p>✅ No findings — all checks passed.</p>';
    }

    html += '<hr style="border-color:#1e2d4a;margin-top:40px">';
    html += '<p style="color:#5a6478;font-size:0.8rem">Generated by mSAS v2</p>';
    html += '</body></html>';

    return html;
  }

  function escapeHtml(str) {
    return MSAS.Utils ? MSAS.Utils.escapeHtml(str) : (str || '');
  }

  /**
   * Generate an executive PDF report using jsPDF.
   * @param {Object} options - { appName, auditorType, results, findings }
   * @param {Object} results - Analysis results
   * @returns {Promise<Blob|null>} PDF blob or null if jsPDF unavailable
   */
  function generateExecutivePdf(options) {
    if (typeof jspdf === 'undefined' && typeof window.jspdf === 'undefined') {
      return null;
    }

    var doc = new (window.jspdf ? window.jspdf.jsPDF : jspdf.jsPDF)({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4'
    });

    var opts = options || {};
    var results = opts.results || [];
    var summary = summarize(results);
    var pageW = 210;
    var margin = 20;
    var contentW = pageW - margin * 2;
    var y = margin;
    var pageH = 297;
    var lineH = 6;

    function addPageIfNeeded(needed) {
      if (y + needed > pageH - margin) {
        doc.addPage();
        y = margin;
      }
    }

    // Title
    doc.setFontSize(22);
    doc.setTextColor(99, 102, 241);
    doc.text('mSAS Security Report', margin, y);
    y += 10;

    doc.setFontSize(10);
    doc.setTextColor(100, 100, 120);
    doc.text('App: ' + (opts.appName || 'Unknown') + '  |  Auditor: ' + (opts.auditorType || 'General') + '  |  ' + new Date().toLocaleDateString(), margin, y);
    y += 8;

    doc.setDrawColor(99, 102, 241);
    doc.setLineWidth(0.5);
    doc.line(margin, y, pageW - margin, y);
    y += 8;

    // Score
    doc.setFontSize(36);
    doc.setTextColor(summary.score >= 70 ? 34 : summary.score >= 40 ? 234 : 239, summary.score >= 70 ? 197 : 179, 94);
    doc.text(summary.score + '/100', margin, y);
    y += 2;
    doc.setFontSize(14);
    doc.setTextColor(100, 100, 120);
    doc.text('Grade: ' + summary.grade, margin + 40, y + 2);
    y += 10;

    // Summary stats
    doc.setFontSize(12);
    doc.setTextColor(200, 200, 220);
    doc.text('Total Checks: ' + summary.total + '  |  Passed: ' + summary.passed + '  |  Failed: ' + summary.failed, margin, y);
    y += 8;

    // Severity breakdown
    doc.setFontSize(14);
    doc.setTextColor(220, 220, 240);
    doc.text('Severity Breakdown', margin, y);
    y += 7;

    var sevs = ['critical', 'high', 'medium', 'low', 'info'];
    var sevColors = { critical: [239, 68, 68], high: [249, 115, 22], medium: [234, 179, 8], low: [34, 197, 94], info: [59, 130, 246] };
    var maxCount = Math.max(1, summary.bySeverity.critical || 0, summary.bySeverity.high || 0,
                             summary.bySeverity.medium || 0, summary.bySeverity.low || 0);
    for (var s = 0; s < sevs.length; s++) {
      var sev = sevs[s];
      var count = summary.bySeverity[sev] || 0;
      var barW = maxCount > 0 ? (count / maxCount) * contentW * 0.6 : 0;
      doc.setFontSize(10);
      doc.setTextColor(sevColors[sev][0], sevColors[sev][1], sevColors[sev][2]);
      doc.text(sev.charAt(0).toUpperCase() + sev.slice(1), margin, y + 1);
      if (barW > 0) {
        doc.setFillColor(sevColors[sev][0], sevColors[sev][1], sevColors[sev][2]);
        doc.rect(margin + 40, y - 1.5, barW, 4, 'F');
      }
      doc.setFontSize(10);
      doc.setTextColor(150, 150, 180);
      doc.text(String(count), margin + 45 + (barW || 0), y + 1);
      y += lineH;
    }
    y += 4;

    // Findings
    var findings = opts.findings || results.filter(function(r) { return !r.passed; });
    if (findings && findings.length > 0) {
      addPageIfNeeded(20);
      doc.setFontSize(14);
      doc.setTextColor(220, 220, 240);
      doc.text('Findings (' + findings.length + ')', margin, y);
      y += 8;

      var maxFindings = Math.min(findings.length, 50);
      for (var f = 0; f < maxFindings; f++) {
        addPageIfNeeded(12);
        var finding = findings[f];
        var sevColor = sevColors[finding.severity] || [100, 100, 120];
        doc.setFontSize(8);
        doc.setTextColor(sevColor[0], sevColor[1], sevColor[2]);
        doc.text('[' + (finding.severity || 'info').toUpperCase() + ']', margin, y);
        doc.setFontSize(10);
        doc.setTextColor(200, 200, 220);
        var title = (finding.title || finding.ruleName || 'Unknown Finding').substring(0, 80);
        doc.text(title, margin + 20, y);
        y += 5;
        doc.setFontSize(8);
        doc.setTextColor(130, 130, 160);
        var desc = (finding.description || '').substring(0, 160);
        doc.text(desc, margin + 20, y);
        y += lineH;
      }
      if (findings.length > 50) {
        doc.setFontSize(9);
        doc.setTextColor(130, 130, 160);
        doc.text('… and ' + (findings.length - 50) + ' more findings', margin, y);
        y += 6;
      }
    }

    // Footer
    addPageIfNeeded(10);
    doc.setDrawColor(99, 102, 241);
    doc.setLineWidth(0.3);
    doc.line(margin, y, pageW - margin, y);
    y += 4;
    doc.setFontSize(8);
    doc.setTextColor(100, 100, 130);
    doc.text('Generated by mSAS v2 — Mobile Security Analysis Suite', margin, y);

    return doc.output('blob');
  }

  return {
    summarize:          summarize,
    generateReportText: generateReportText,
    generateReportHtml: generateReportHtml,
    generateExecutivePdf: generateExecutivePdf
  };
})();
